#!/usr/bin/env python3
"""Build deterministic Unicode-range WOFF2 slices for the CJK code fallback."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from fontTools import __version__ as fonttools_version
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path, help="NotoSansMonoCJKkr-VF.ttf")
    parser.add_argument("output", type=Path, help="directory for WOFF2 slices")
    parser.add_argument("css", type=Path, help="generated CSS file")
    return parser.parse_args()


def source_codepoints(path: Path) -> set[int]:
    font = TTFont(path, lazy=True, recalcTimestamp=False)
    try:
        return {codepoint for table in font["cmap"].tables if table.isUnicode() for codepoint in table.cmap}
    finally:
        font.close()


def subset_font(source: Path, target: Path, codepoints: set[int]) -> None:
    options = Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.notdef_outline = False
    options.recommended_glyphs = False

    font = TTFont(source, recalcTimestamp=False)
    subsetter = Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(target, reorderTables=True)
    font.close()


def main() -> None:
    args = parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    args.css.parent.mkdir(parents=True, exist_ok=True)
    for stale_slice in args.output.glob("subset-*.woff2"):
        stale_slice.unlink()

    codepoints = source_codepoints(args.input)
    groups: dict[int, set[int]] = {}
    for codepoint in codepoints:
        groups.setdefault(codepoint >> 9, set()).add(codepoint)

    css = [
        "/* Generated by scripts/build-cjk-code-font.py with FontTools "
        + fonttools_version
        + ". */",
        "",
    ]
    checksums: list[str] = []
    for page, codepoints in sorted(groups.items()):
        start = page << 9
        end = start + 0x1FF
        filename = f"subset-{start:06x}-{end:06x}.woff2"
        target = args.output / filename
        subset_font(args.input, target, codepoints)
        digest = hashlib.sha256(target.read_bytes()).hexdigest()
        checksums.append(f"{digest}  {filename}")
        css.extend(
            [
                "@font-face {",
                "  font-family: 'Noto Sans Mono CJK KR';",
                "  font-style: normal;",
                "  font-display: swap;",
                "  font-weight: 400 700;",
                f"  src: url('/fonts/noto-cjk/subsets/{filename}') format('woff2-variations');",
                f"  unicode-range: U+{start:X}-{end:X};",
                "}",
                "",
            ]
        )

    args.css.write_text("\n".join(css), encoding="utf-8")
    (args.output / "SHA256SUMS").write_text("\n".join(checksums) + "\n", encoding="utf-8")
    print(f"wrote {len(groups)} WOFF2 slices with {len(codepoints)} mapped codepoints")


if __name__ == "__main__":
    main()
